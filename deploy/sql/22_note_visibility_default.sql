-- =============================================================
-- 笔记默认可见性改为公开（已有数据库执行一次，可选）
-- 适用：MySQL 8.0+，执行前请先选中 stellar_ink 数据库
--
-- 背景：
--   可见性的“默认值”此前是 PRIVATE，导致新写的技术笔记默认藏起来，
--   全站搜索、标签聚合、RSS 里都看不到 —— 技术线因此只能算私人标本册。
--   代码侧已改（NoteVisibility.defaultForCreate：未传 visibility 时 PUBLIC，
--   传了不认识的值仍回退 PRIVATE），这里同步改库级默认值，让“直接写库”也不会掉回旧口径。
--
-- 影响面（重要）：
--   · 只影响**未来**插入且**没有显式写 visibility 列**的行；
--     已存在的私有笔记不会被改成公开（这条脚本刻意不 UPDATE 任何数据）。
--   · 想批量公开历史笔记请自己决定要公开哪些 id，不要整表 UPDATE：
--     那会把作者当初明确选择的“私有”一并推翻。
--
-- 例：只公开某几条（确认过内容可以公开再执行）
--   UPDATE `note` SET `visibility` = 'PUBLIC' WHERE `id` IN (11, 12, 13);
-- =============================================================

SET NAMES utf8mb4;

ALTER TABLE `note` ALTER COLUMN `visibility` SET DEFAULT 'PUBLIC';
